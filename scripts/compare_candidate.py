"""Shipped detector vs candidate detector, side by side: writes results/candidate/COMPARISON.md.

  python scripts/compare_candidate.py

Every number is read from a result file (nothing is typed by hand), and every file is checked to belong to the model it
is attributed to (SHA-256 of the model file). Missing files are reported as "not run", never guessed.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAMS = ("resample", "splice", "copy_move", "inpaint")


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def auc(x):
    return "n/a" if not x else f"{x['auc_roc']:.3f}"


def fused(metrics):
    if metrics is None:
        return None
    k = [m for m in metrics["models"] if m.startswith("fused")]
    return metrics["models"][k[0]] if k else None


def val_recall(log: Path):
    """Best fused validation recall at the target FPR, read from a train_log.txt."""
    if not log.exists():
        return None, None
    txt = log.read_text()
    vals = [(float(w), float(r)) for w, r in re.findall(r"fusion w_features=([\d.]+): val recall at \d+% FPR = ([\d.]+)",
                                                          txt)]
    if not vals:
        return None, None
    w, r = max(vals, key=lambda t: t[1])
    plain = re.search(r"without test-time averaging: best val recall at \d+% FPR = ([\d.]+)", txt)
    return r, float(plain.group(1)) if plain else None


def check(doc, sha, what, problems):
    if doc is not None and doc.get("model_sha256") not in (None, sha):
        problems.append(f"{what}: belongs to model {doc['model_sha256'][:12]}, not {sha[:12]}: ignored")
        return None
    return doc


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--shipped-results", default=str(ROOT / "results"))
    ap.add_argument("--candidate-results", default=str(ROOT / "results" / "candidate"))
    ap.add_argument("--shipped-models", default=str(ROOT / "models"))
    ap.add_argument("--candidate-models", default=str(ROOT / "models_candidate"))
    a = ap.parse_args()
    S, C = Path(a.shipped_results), Path(a.candidate_results)
    card_s = load(Path(a.shipped_models) / "detector.json")
    card_c = load(Path(a.candidate_models) / "detector.json")
    if card_s is None or card_c is None:
        sys.exit("both models/detector.json and models_candidate/detector.json are needed")
    sha_s, sha_c = card_s["sha256"], card_c["sha256"]
    problems: list[str] = []

    ms, mc = load(S / "metrics.json"), load(C / "metrics.json")
    if mc is not None and mc.get("card", {}).get("sha256") != sha_c:
        problems.append("candidate metrics.json was computed for another model: ignored")
        mc = None
    fs, fc = fused(ms), fused(mc)
    v2s = check(load(S / "heldout_v2_v2model.json"), sha_s, "shipped held-out v2", problems)
    v2c = check(load(S / "heldout_v2_candidate.json"), sha_c, "candidate held-out v2", problems)
    v3s = check(load(S / "heldout_v3_shipped.json"), sha_s, "shipped held-out v3", problems)
    v3c = check(load(S / "heldout_v3_candidate.json"), sha_c, "candidate held-out v3", problems)
    rs, rc = load(S / "robustness.json"), load(C / "robustness.json")
    vs, _ = val_recall(S / "train_log.txt")
    vc, vc_plain = val_recall(C / "train_log.txt")
    cnn_line = re.search(r"CNN: (.*)", (C / "train_log.txt").read_text()) if (C / "train_log.txt").exists() else None
    params = re.search(r"\(([\d,]+) parameters\)", (C / "train_log.txt").read_text()) \
        if (C / "train_log.txt").exists() else None

    L = ["# Shipped detector vs candidate detector", "",
         "Generated by `scripts/compare_candidate.py` from the result files (no number typed by hand). The shipped model "
         "is the one every report number comes from; the candidate is NOT shipped unless the team adopts it.", "",
         "| | Shipped | Candidate |", "|---|---|---|",
         f"| model file SHA-256 | `{sha_s[:16]}…` | `{sha_c[:16]}…` |",
         f"| training edits | dev | dev + dev_plus |",
         f"| CNN | width 16, 74,116 parameters, 8 epochs, best val accuracy | "
         f"{cnn_line.group(1) if cnn_line else 'n/a'}; {params.group(1) if params else '?'} parameters |",
         f"| test-time averaging | no | {'yes' if card_c.get('cnn_tta') else 'no'} |",
         f"| fusion weight (features) | {card_s['w_gbm']} | {card_c['w_gbm']} |", ""]

    L += ["## 1. Validation (the only basis for choices)", "",
          "Best fused recall at 5% false alarms on the validation split. **Not directly comparable between the two "
          "columns**: the candidate's validation set also contains dev_plus edits. It was used to choose the candidate's "
          "epochs, fusion weight and test-time averaging, never the test sets below.", "",
          "| | Shipped | Candidate |", "|---|---|---|",
          f"| val recall @5% FPR | {'n/a' if vs is None else f'{vs:.4f}'} | {'n/a' if vc is None else f'{vc:.4f}'} |"]
    if vc_plain is not None:
        L.append(f"| candidate without test-time averaging | | {vc_plain:.4f} |")
    L.append("")

    L += ["## 2. Test sets (fused model, each set opened once per model)", "",
          "| Set | Shipped detection | Shipped false alarms | Candidate detection | Candidate false alarms | "
          "Shipped AUC | Candidate AUC |", "|---|---|---|---|---|---|---|"]
    names = {"test_dev": "seen variants (test_dev)", "test_heldout": "held-out v1",
             "test_dev_laundered": "seen + laundering", "test_heldout_laundered": "held-out v1 + laundering"}
    for k, label in names.items():
        a_, b_ = (fs or {}).get(k), (fc or {}).get(k)
        L.append(f"| {label} | {pct(a_ and a_['detection_rate'])} | {pct(a_ and a_['false_alarm_rate'])} | "
                 f"{pct(b_ and b_['detection_rate'])} | {pct(b_ and b_['false_alarm_rate'])} | {auc(a_)} | {auc(b_)} |")
    for title, xs, xc, note in (
            ("held-out v2", v2s, v2c, "biased: already used to measure the changes after v1 (KNOWN_LIMITATIONS #14)"),
            ("**held-out v3** (frozen before the candidate was trained)", v3s, v3c, "first and only look")):
        a_, b_ = (xs or {}).get("models", {}).get("fused"), (xc or {}).get("models", {}).get("fused")
        L.append(f"| {title} ({note}) | {pct(a_ and a_['detection_rate'])} | {pct(a_ and a_['false_alarm_rate'])} | "
                 f"{pct(b_ and b_['detection_rate'])} | {pct(b_ and b_['false_alarm_rate'])} | {auc(a_)} | {auc(b_)} |")
    L.append("")

    L += ["## 3. Detection by manipulation family (fused)", "",
          "| Set | Family | Shipped | Candidate |", "|---|---|---|---|"]
    for label, a_, b_ in (("held-out v1", (fs or {}).get("test_heldout"), (fc or {}).get("test_heldout")),
                          ("held-out v2 (biased)", (v2s or {}).get("models", {}).get("fused"),
                           (v2c or {}).get("models", {}).get("fused")),
                          ("held-out v3", (v3s or {}).get("models", {}).get("fused"),
                           (v3c or {}).get("models", {}).get("fused"))):
        for f in FAMS:
            L.append(f"| {label} | {f} | {pct(a_ and a_['detection_by_family'].get(f))} | "
                     f"{pct(b_ and b_['detection_by_family'].get(f))} |")
    L.append("")

    L += ["## 4. Robustness (one operation applied to every patch)", "",
          "| Operation | Seen in training | Shipped false alarms | Shipped detection | Candidate false alarms | "
          "Candidate detection |", "|---|---|---|---|---|---|"]
    rows_c = {r["condition"]: r for r in (rc or {}).get("rows", [])}
    for r in (rs or {}).get("rows", []):
        c = rows_c.get(r["condition"])
        L.append(f"| {r['condition']} | {'yes' if r['seen_in_training'] else 'NO'} | {pct(r['false_alarm_rate'])} | "
                 f"{pct(r['detection_rate'])} | {pct(c and c['false_alarm_rate'])} | {pct(c and c['detection_rate'])} |")
    L.append("")

    es, ec = (ms or {}).get("efficiency", {}), (mc or {}).get("efficiency", {})
    L += ["## 5. Cost (single CPU core)", "",
          "| | Shipped | Candidate |", "|---|---|---|",
          f"| analysis per patch, p50 (no heatmap) | {es.get('analyse_ms_p50', float('nan')):.1f} ms | "
          f"{ec.get('analyse_ms_p50', float('nan')):.1f} ms |",
          f"| peak memory | {es.get('peak_rss_mb', float('nan')):.0f} MB | {ec.get('peak_rss_mb', float('nan')):.0f} MB |",
          "", "The shipped figures were measured on Linux and the candidate's on Windows (different memory counters and "
          "machine): compare the latency only as an order of magnitude.", ""]

    if problems:
        L += ["## Problems found while reading the files", ""] + [f"- {p}" for p in problems] + [""]
    L += ["## How to read this", "",
          "- Adopt the candidate only if it is better on held-out v3 (the only unbiased test) without more false alarms, "
          "and then follow the adoption steps in `runtime/retrained_model_backup_2026-11-02/README.txt` (every report "
          "number changes).",
          "- Try it live without adopting it: `$env:PIXELPROOF_MODEL=\"models_candidate\\detector.joblib\"` before "
          "`uvicorn`."]
    out = C / "COMPARISON.md"
    out.write_text("\n".join(L) + "\n")
    print(out.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
